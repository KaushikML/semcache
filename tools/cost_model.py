#!/usr/bin/env python3
"""Cost model for semcache (Phase 7): upstream spend saved vs proxy compute spent.

Measured inputs (read from bench/results/phase7):
  - semantic recall and false-hit rate at the chosen threshold (threshold.json, QQP)
  - embedding throughput of the product embedder (load_semantic_hit.json: embed-bound HITs/s)
Assumptions (parameters, NOT measurements; change them for your traffic and provider):
  - traffic volume, tokens per request, token prices, vCPU price,
  - the share of exact repeats and of near-duplicates in the traffic (workload-dependent).

Writes bench/results/phase7/cost_model.md.
Usage: .venv/bin/python tools/cost_model.py [--threshold 0.97] [--requests 10e6] ...
"""

import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "bench/results/phase7"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--threshold", type=float, default=0.97)
    ap.add_argument("--requests", type=float, default=10e6, help="requests per month (assumption)")
    ap.add_argument("--prompt-tokens", type=float, default=500, help="input tokens per request (assumption)")
    ap.add_argument("--completion-tokens", type=float, default=200, help="output tokens per request (assumption)")
    ap.add_argument("--usd-per-1m-input", type=float, default=0.15,
                    help="example price; set your provider's current price (assumption)")
    ap.add_argument("--usd-per-1m-output", type=float, default=0.60,
                    help="example price; set your provider's current price (assumption)")
    ap.add_argument("--usd-per-vcpu-hour", type=float, default=0.04, help="compute price (assumption)")
    args = ap.parse_args()

    thr = json.loads((RES / "threshold.json").read_text())
    row = min(thr["qqp"]["curve"], key=lambda r: abs(r["threshold"] - args.threshold))
    recall, false_hit = row["recall"], row["false_hit_rate"]
    sem = json.loads((RES / "load_semantic_hit.json").read_text())
    # Semantic HITs are embed-bound: rps with N embed threads => CPU-seconds per embed.
    embed_threads = 4
    cpu_s_per_embed = embed_threads / sem["loadgen"]["rps"]

    cost_per_req = (args.prompt_tokens * args.usd_per_1m_input + args.completion_tokens * args.usd_per_1m_output) / 1e6
    baseline = args.requests * cost_per_req

    lines = [
        "# Cost model (Phase 7)",
        "",
        "Generated by `tools/cost_model.py`. **Measured** inputs: QQP recall and false-hit rate at the",
        f"threshold ({args.threshold:.2f}: recall {recall:.3f}, false-hit {false_hit:.4f}; `threshold.json`) and",
        f"embedding cost ({cpu_s_per_embed * 1000:.1f} CPU-ms per embed from `load_semantic_hit.json`).",
        "**Assumptions** (parameters, not measurements): "
        f"{args.requests / 1e6:.0f}M requests/month, {args.prompt_tokens:.0f} input + "
        f"{args.completion_tokens:.0f} output tokens per request, ${args.usd_per_1m_input}/1M input and "
        f"${args.usd_per_1m_output}/1M output tokens (example list prices, check your provider), "
        f"${args.usd_per_vcpu_hour}/vCPU-hour.",
        "",
        f"Without the cache: **${baseline:,.0f}/month** upstream.",
        "",
        "The traffic mix decides almost everything, and it is unknown in general: `exact` is the share",
        "of requests that repeat an earlier one verbatim (served by the exact fast path, no embedding,",
        "no false-hit risk); `near-dup` is the share that is a rewording of an earlier one (caught",
        "with probability = recall); `look-alike` is the share that resembles an earlier request but",
        "needs a different answer (wrongly served with probability = false-hit rate).",
        "",
        "| exact | near-dup | look-alike | hit rate | upstream $/month | saved $/month | proxy CPU $/month | wrong answers / month |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for exact, near, alike in [(0.0, 0.10, 0.10), (0.10, 0.10, 0.10), (0.30, 0.10, 0.10), (0.50, 0.10, 0.10),
                               (0.30, 0.30, 0.10), (0.30, 0.10, 0.30)]:
        semantic_hits = near * recall
        wrong = alike * false_hit
        hit_rate = exact + semantic_hits + wrong
        upstream = baseline * (1 - hit_rate)
        embeds = args.requests * (1 - exact)  # every non-exact request is embedded once
        cpu = embeds * cpu_s_per_embed / 3600 * args.usd_per_vcpu_hour
        lines.append(f"| {exact:.0%} | {near:.0%} | {alike:.0%} | {hit_rate:.1%} | {upstream:,.0f} | "
                     f"{baseline - upstream:,.0f} | {cpu:,.0f} | {args.requests * wrong:,.0f} |")
    lines += [
        "",
        "**Reading it**",
        "- With all-MiniLM-L6-v2 at the safe threshold, savings come mostly from **exact repeats**",
        f"  (and from coalescing herds); semantic matching adds `near-dup × {recall:.2f}`.",
        "- The embedding CPU is small next to upstream spend at these prices, but it is spent on every",
        "  non-exact request, hit or not.",
        "- Wrong answers scale with how much look-alike traffic there is; lowering the threshold raises",
        "  both semantic hits and wrong answers (see `threshold_qqp.png`).",
        "- Coalescing is a separate saving for bursts of identical requests in flight together",
        "  (`load_herd_*.json`): N concurrent duplicates cost one upstream call instead of N.",
    ]
    (RES / "cost_model.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
