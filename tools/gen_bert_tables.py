#!/usr/bin/env python3
"""Derives the BERT character classes from HuggingFace `tokenizers` itself (ADR-004).

HF's Rust tokenizer uses Unicode tables older than any current library (e.g. Cn and most Mc are
kept, U+1734 is stripped), so general categories from utf8proc cannot reproduce it exactly. Instead we
probe every code point through HF's normalizer and pre-tokenizer and emit:

  src/embed/bert_tables.inc          range tables: removed, whitespace, CJK-padded, mapped (NFD/case),
                                     punctuation, split
  tests/data/normalizer_blocks.txt   SHA-256 of HF's normalized output per 4096-code-point block,
                                     so a C++ test can check all 1.1M code points exhaustively

Usage: .venv/bin/python tools/gen_bert_tables.py
       .venv/bin/python tools/gen_bert_tables.py --diff <block dump written by the C++ test>
"""

import argparse
import hashlib
import pathlib

REPO = "sentence-transformers/all-MiniLM-L6-v2"
REVISION = "1110a243fdf4706b3f48f1d95db1a4f5529b4d41"  # keep in sync with scripts/fetch-model.sh
ROOT = pathlib.Path(__file__).resolve().parent.parent
BLOCK = 4096
MAX_CP = 0x110000


def code_points():
    return (cp for cp in range(MAX_CP) if not 0xD800 <= cp <= 0xDFFF)


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emit(name, comment, cps):
    rs = ranges(cps)
    body = "\n".join(f"    {{0x{lo:04X}, 0x{hi:04X}}}," for lo, hi in rs)
    return f"// {comment} ({len(cps)} code points)\ninline constexpr CodepointRange {name}[] = {{\n{body}\n}};\n"


def diff(path, norm):
    """Lists code points where the C++ normalizer (dump from the test) disagrees with HF."""
    shown = 0
    for line in pathlib.Path(path).read_text().splitlines():
        cp_hex, _, rest = line.partition(":")
        ours = "".join(chr(int(x, 16)) for x in rest.split())
        theirs = norm.normalize_str(chr(int(cp_hex, 16)))
        if ours != theirs:
            shown += 1
            fmt = lambda s: " ".join(f"{ord(c):04X}" for c in s) or "(empty)"
            print(f"U+{cp_hex.upper():>04}  hf: {fmt(theirs):<24} ours: {fmt(ours)}")
    print(f"{shown} differences")


def main():
    from transformers import AutoTokenizer

    ap = argparse.ArgumentParser()
    ap.add_argument("--diff", metavar="DUMP")
    args = ap.parse_args()

    tok = AutoTokenizer.from_pretrained(REPO, revision=REVISION, use_fast=True)
    norm = tok.backend_tokenizer.normalizer
    if args.diff:
        diff(args.diff, norm)
        return
    pre = tok.backend_tokenizer.pre_tokenizer

    removed, space, cjk, mapped, punct, split = set(), set(), set(), set(), set(), set()
    hashes = {}
    h = hashlib.sha256()
    for cp in code_points():
        if cp % BLOCK == 0:
            h = hashlib.sha256()
            hashes[cp] = h
        c = chr(cp)
        out = norm.normalize_str(c)
        h.update(out.encode("utf-8") + b"\0")
        if out == "":
            removed.add(cp)
        elif out == " ":
            space.add(cp)
        else:
            core = out
            if len(out) >= 3 and out[0] == " " and out[-1] == " ":
                cjk.add(cp)
                core = out[1:-1]
            if core != c:
                mapped.add(cp)

        pieces = [p for p, _ in pre.pre_tokenize_str("a" + c + "b")]
        if pieces == ["a", c, "b"]:
            punct.add(cp)
        elif pieces == ["a", "b"]:
            split.add(cp)
        elif pieces != ["a" + c + "b"]:
            raise SystemExit(f"unexpected pre-tokenization of U+{cp:04X}: {pieces}")

    header = (
        "// GENERATED by tools/gen_bert_tables.py from HuggingFace tokenizers "
        f"({REPO}@{REVISION[:12]}). Do not edit.\n"
        "// Included by wordpiece_tokenizer.cpp; each table is sorted, non-overlapping and inclusive.\n\n"
    )
    tables = [
        emit("kRemoved", "normalizer drops: control/format chars, stripped marks, U+FFFD", removed),
        emit("kWhitespace", "normalizer maps to ' '", space),
        emit("kCjkPadded", "normalizer surrounds with spaces (CJK ideographs)", cjk),
        emit("kMapped", "normalizer changes via NFD / mark stripping / lowercasing; all others pass through", mapped),
        emit("kPunctuation", "pre-tokenizer isolates as a single-char word", punct),
        emit("kSplitSpace", "pre-tokenizer splits on and drops", split),
    ]
    (ROOT / "src/embed/bert_tables.inc").write_text(header + "\n".join(tables))

    lines = [f"{start:06X} {hashes[start].hexdigest()}" for start in sorted(hashes)]
    (ROOT / "tests/data/normalizer_blocks.txt").write_text(
        "# block_start sha256(concat(utf8(normalize(chr(cp))) + NUL for cp in block, surrogates skipped))\n"
        + "\n".join(lines) + "\n")
    print(f"removed={len(removed)} whitespace={len(space)} cjk={len(cjk)} mapped={len(mapped)} punct={len(punct)} "
          f"split={len(split)} blocks={len(hashes)}")


if __name__ == "__main__":
    main()
